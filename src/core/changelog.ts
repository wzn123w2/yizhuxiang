export const latestNoticeId = (): string => CHANGELOG[0]?.id ?? '';

/**
 * 比"看过的 id"更新的条目。
 * 没看过、或者本地记的 id 已经不在列表里（回滚过版本）时，只给最新一条，
 * 免得一上来砸一屏更新内容。
 */
export function unseenEntries(seenId: string | undefined): ChangelogEntry[] {
  if (!seenId) return CHANGELOG.slice(0, 1);
  const i = CHANGELOG.findIndex((e) => e.id === seenId);
  if (i === -1) return CHANGELOG.slice(0, 1);
  return CHANGELOG.slice(0, i);
}
