/** 最近给过的那一个，别连着出同一个 */
let last = '';

/**
 * 掷一个法号。
 * @param avoid 不想要的结果（通常是输入框里现在这个）
 */
export function randomDharmaName(avoid = ''): string {
  for (let i = 0; i < 40; i++) {
    const name = NAMES[(Math.random() * NAMES.length) | 0];
    if (name === avoid || name === last) continue;
    last = name;
    return name;
  }
  const fallback = NAMES[0];
  last = fallback;
  return fallback;
}

